/* ============================================
   DOMContentLoaded
   ============================================ */
document.addEventListener("DOMContentLoaded", () => {
  const lang = document.documentElement.lang || "ja";
  const content = window.siteContent?.[lang] || window.siteContent?.ja;

  const detailLabels = {
    ja: "詳しく→",
    en: "Details→",
    tl: "Detalye→",
    id: "Detail→"
  };
  const detailLabel = detailLabels[lang] || "詳しく→";

  // ── News ──
  const newsList = document.getElementById("newsList");
  if (newsList && Array.isArray(content?.news)) {
    newsList.innerHTML = content.news.map(item => {
      const detailBtn = item.url
        ? ` <a href="${item.url}" class="news-detail-btn">${detailLabel}</a>`
        : "";
      return `
        <li>
          <span class="news-date">${item.date || ""}</span>
          <span class="news-text">${item.text || ""}${detailBtn}</span>
        </li>
      `;
    }).join("");
  }

  // ── Announcements ──
  const announcementList = document.getElementById("announcementList");
  if (announcementList && Array.isArray(content?.announcements)) {
    announcementList.innerHTML = content.announcements.map(item => {
      const detailBtn = item.url
        ? ` <a href="${item.url}" class="news-detail-btn">${detailLabel}</a>`
        : "";
      return `
        <li>
          <span class="news-date">${item.date || ""}</span>
          <span class="announcement-text">${item.text || ""}${detailBtn}</span>
        </li>
      `;
    }).join("");
  }

  // ── News & Topics（トップページ：お知らせ＋ニュースを日付順に統合） ──
  const topicsList = document.getElementById("topicsList");
  if (topicsList && content) {
    const typeLabels = { announcements: "お知らせ", news: "入管・制度" };
    const toTime = d => {
      const [y, m = 1, day = 1] = String(d || "").split(".").map(Number);
      return new Date(y, m - 1, day).getTime() || 0;
    };
    const NEW_DAYS = 45;
    const items = ["announcements", "news"]
      .flatMap(type => (content[type] || []).map(item => ({ ...item, type })))
      .filter(item => !item.featured)
      .sort((a, b) => toTime(b.date) - toTime(a.date));

    const render = filter => {
      const list = items.filter(item => filter === "all" || item.type === filter).slice(0, 6);
      topicsList.innerHTML = list.map(item => {
        const isNew = Date.now() - toTime(item.date) < NEW_DAYS * 86400000;
        const external = /^https?:/.test(item.url || "");
        const inner = `
          <span class="lp-news-date">${item.date || ""}</span>
          <span class="lp-news-cat lp-news-cat--${item.type}">${typeLabels[item.type]}</span>
          ${isNew ? '<span class="lp-pill lp-pill--new">NEW</span>' : ""}
          <span class="lp-news-text">${item.text || ""}</span>`;
        return item.url
          ? `<li><a href="${item.url}"${external ? ' target="_blank" rel="noopener"' : ""}>${inner}<i class="fa-solid fa-chevron-right lp-news-arrow"></i></a></li>`
          : `<li><div>${inner}</div></li>`;
      }).join("");
    };

    document.querySelectorAll(".lp-news-tab").forEach(tab => {
      tab.addEventListener("click", () => {
        document.querySelectorAll(".lp-news-tab").forEach(t => {
          const active = t === tab;
          t.classList.toggle("is-active", active);
          t.setAttribute("aria-selected", String(active));
        });
        render(tab.dataset.filter);
      });
    });
    render("all");
  }

  // ── Q&A ──
  const qaList = document.getElementById("qaList");
  if (qaList && Array.isArray(content?.qa)) {
    qaList.innerHTML = content.qa.map((item, index) => `
      <div class="qa-item">
        <button class="qa-question" type="button"
                aria-expanded="false"
                aria-controls="qa-answer-${index}">
          ${item.q}
        </button>
        <div class="qa-answer" id="qa-answer-${index}" hidden>
          <p>${item.a}</p>
        </div>
      </div>
    `).join("");

    qaList.querySelectorAll(".qa-question").forEach(btn => {
      btn.addEventListener("click", () => {
        const answer = document.getElementById(btn.getAttribute("aria-controls"));
        const expanded = btn.getAttribute("aria-expanded") === "true";
        btn.setAttribute("aria-expanded", String(!expanded));
        if (answer) answer.hidden = expanded;
      });
    });
  }
});
